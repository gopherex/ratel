// The quick start mirrors README.md; examples/shop runs the complete program in CI.
const schema = `CREATE SCHEMA app;

CREATE TABLE app.users (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name  text NOT NULL
);

CREATE TABLE app.orders (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users (id),
    total   numeric(12, 2) NOT NULL
);

CREATE INDEX orders_user_id_idx ON app.orders (user_id);`;

const queries = `-- name: TopCustomers :many
SELECT u.email, sum(o.total) AS spent
FROM app.users u JOIN app.orders o ON o.user_id = u.id
GROUP BY u.email
ORDER BY spent DESC
LIMIT @limit;`;

const commands = `ratel init                 # ratel.yaml, schema/, queries/, migrations/
ratel generate             # typed Go code
ratel migrate plan init    # a planned, checksummed migration`;

const usage = `err := migrate.Apply(ctx, pool, dir) // no table is locked longer than a moment

db := ratel.New(pool)

ann, err := db.Run(app.Users.Select().
	Where(app.Users.Email.Eq("ann@example.com")).
	With(app.Users.Orders)). // two queries, no N+1
	One(ctx)

top, err := db.Run(users.TopCustomers().Limit(10)).List(ctx)`;

