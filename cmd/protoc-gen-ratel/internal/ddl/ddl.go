// Package ddl turns ratel-annotated .proto files into PostgreSQL DDL that the
// schema source format of docs/input.md accepts: declarations only, one file
// per .proto, with @ratel.origin on every table and column.
package ddl

import (
	"errors"
	"fmt"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/gopherex/ratel/options"
)

// Generation errors. Each returned error wraps one of them and names the proto
// paths involved; callers branch with errors.Is.
var (
	ErrInvalidOption   = errors.New("invalid ratel option")
	ErrUnsupportedType = errors.New("unsupported proto type")
	ErrDuplicateColumn = errors.New("duplicate column")
	ErrDuplicateObject = errors.New("duplicate object")
	ErrUnknownMessage  = errors.New("unknown message")
	ErrNotTable        = errors.New("message is not a table")
	ErrUnknownField    = errors.New("unknown field")
	ErrEmbedCycle      = errors.New("embed cycle")
)

// registry indexes every message of the request by full name, so a reference
// can name a table declared in any file of the request.
type registry struct {
	messages map[protoreflect.FullName]*protogen.Message
	packages map[protogen.GoImportPath]protogen.GoPackageName // Go package of each file's import path
}

// Generate writes one .sql file for every .proto file the plugin is asked to
// generate. The output depends only on the input descriptors.
func Generate(plugin *protogen.Plugin) error {
	reg := registry{
		messages: make(map[protoreflect.FullName]*protogen.Message),
		packages: make(map[protogen.GoImportPath]protogen.GoPackageName),
	}

	for _, file := range plugin.Files {
		reg.packages[file.GoImportPath] = file.GoPackageName

		for _, msg := range allMessages(file.Messages) {
			reg.messages[msg.Desc.FullName()] = msg
		}
	}

	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}

		sql, err := reg.file(file)
		if err != nil {
			return fmt.Errorf("%s: %w", file.Desc.Path(), err)
		}

		out := plugin.NewGeneratedFile(sqlPath(file.Desc.Path()), "")
		if _, err := out.Write(sql); err != nil {
			return fmt.Errorf("write %s: %w", sqlPath(file.Desc.Path()), err)
		}
	}

	return nil
}

// sqlPath names the output of a .proto file: the same path with a .sql suffix.
func sqlPath(protoPath string) string {
	return strings.TrimSuffix(protoPath, ".proto") + ".sql"
}

// file renders the enum types and tables of one .proto file.
func (r registry) file(file *protogen.File) ([]byte, error) {
	var out strings.Builder

	out.WriteString("-- Code generated by protoc-gen-ratel. DO NOT EDIT.\n")
	out.WriteString("-- source: " + file.Desc.Path() + "\n")

	claimed := make(map[string]string)

	for _, enum := range fileEnums(file) {
		if !pgEnum(enum.Desc) {
			continue
		}

		typeName := enumTypeName(enum.Desc)
		if err := claim(claimed, typeName, string(enum.Desc.FullName())); err != nil {
			return nil, err
		}

		out.WriteString("\nCREATE TYPE " + typeName + " AS ENUM (" + enumLabels(enum) + ");\n")
	}

	for _, msg := range tableMessages(file.Messages) {
		tbl, err := r.buildTable(msg)
		if err != nil {
			return nil, err
		}

		if err := claim(claimed, tbl.name, tbl.origin); err != nil {
			return nil, err
		}

		tbl.render(&out)
	}

	return []byte(out.String()), nil
}

// claim records the proto owner of a schema object and rejects a second owner.
func claim(claimed map[string]string, object, owner string) error {
	if prev, ok := claimed[object]; ok {
		return fmt.Errorf("%w: %s is declared by %s and %s", ErrDuplicateObject, object, prev, owner)
	}

	claimed[object] = owner

	return nil
}

// enumLabels renders the value names of an enum as SQL string literals.
func enumLabels(enum *protogen.Enum) string {
	labels := make([]string, 0, len(enum.Values))
	for _, value := range enum.Values {
		labels = append(labels, sqlString(string(value.Desc.Name())))
	}

	return strings.Join(labels, ", ")
}

// allMessages lists messages and their nested messages in declaration order.
func allMessages(messages []*protogen.Message) []*protogen.Message {
	out := make([]*protogen.Message, 0, len(messages))

	for _, msg := range messages {
		out = append(out, msg)
		out = append(out, allMessages(msg.Messages)...)
	}

	return out
}

// tableMessages lists the messages marked as tables, in declaration order.
func tableMessages(messages []*protogen.Message) []*protogen.Message {
	all := allMessages(messages)
	tables := make([]*protogen.Message, 0, len(all))

	for _, msg := range all {
		if option[*options.Table](msg.Desc.Options(), options.E_Table) != nil && !msg.Desc.IsMapEntry() {
			tables = append(tables, msg)
		}
	}

	return tables
}

// fileEnums lists the top-level enums of a file, then the nested ones.
func fileEnums(file *protogen.File) []*protogen.Enum {
	enums := append([]*protogen.Enum{}, file.Enums...)

	for _, msg := range allMessages(file.Messages) {
		enums = append(enums, msg.Enums...)
	}

	return enums
}
