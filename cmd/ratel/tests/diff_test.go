type diffCase struct {
	name             string
	current, desired string
	intents          diff.Intents
	kinds            []diff.Kind
	kinds18          []diff.Kind // on PostgreSQL 18, when they differ
	namespace        string      // "app" when empty
}

func diffCases(t *testing.T) []diffCase {
	t.Helper()

	shop, err := os.ReadFile("testdata/introspect/schema.sql")
	if err != nil {
		t.Fatal(err)
	}

	return append([]diffCase{
		{
			name: "create everything", desired: string(shop), namespace: "shop",
		},
		{
			name: "drop everything", current: string(shop), namespace: "shop",
		},
	}, objectCases()...)
}

