const partitions = `CREATE TABLE app.solo (id int);
	CREATE TABLE app.p (k int NOT NULL) PARTITION BY RANGE (k);
	CREATE TABLE app.p1 PARTITION OF app.p FOR VALUES FROM (0) TO (10);`

// TestDiff applies each case's current and desired schema to their own dev
// databases, applies the diff to the current one and checks that it then
// renders as the desired one.
func TestDiff(t *testing.T) {
	t.Parallel()

	cases := diffCases(t)

	for _, major := range []int{16, 17, 18} {
		t.Run(strconv.Itoa(major), func(t *testing.T) {
			t.Parallel()

			pool := postgresPool(t, major)

			ctx, cancel := context.WithTimeout(t.Context(), startupTimeout)
			defer cancel()

			if _, err := pool.Exec(ctx, `CREATE ROLE ratel_reader`); err != nil {
				t.Fatal(err)
			}

			server, err := devdb.Start(ctx, config.Dev{URL: pool.Config().ConnString()})
			if err != nil {
				t.Fatal(err)
			}

			defer func() { _ = server.Close(context.WithoutCancel(ctx)) }()

			for _, item := range cases {
				t.Run(item.name, func(t *testing.T) { checkDiff(ctx, t, server, item) })
			}
		})
	}
}

func checkDiff(ctx context.Context, t *testing.T, server *devdb.Server, item diffCase) {
	t.Helper()

	namespaces := []string{"app"}
	if item.namespace != "" {
		namespaces = []string{item.namespace}
	}

	current := applied(ctx, t, server, namespaces, item.current)
	desired := applied(ctx, t, server, namespaces, item.desired)
	want := render(ctx, t, desired, namespaces)

	changes := diff.Diff(render(ctx, t, current, namespaces), want, item.intents)

	kinds := make([]diff.Kind, 0, len(changes))

	for _, change := range changes {
		kinds = append(kinds, change.Kind)

		if _, err := current.Pool.Exec(ctx, "SET check_function_bodies = off;\n"+change.SQL); err != nil {
			t.Fatalf("%s %s: %v\n%s", change.Kind, change.Key, err, change.SQL)
		}
	}

	expected := item.kinds
	if item.kinds18 != nil && want.Major == 18 {
		expected = item.kinds18
	}

	if expected != nil {
		if difference := cmp.Diff(expected, kinds); difference != "" {
			t.Errorf("kinds (-want +got):\n%s", difference)
		}
	}

	got := render(ctx, t, current, namespaces)
	for _, part := range []struct {
		name      string
		want, got any
	}{
		{"objects", want.Objects, got.Objects},
		{"columns", want.Columns, got.Columns},
		{"domains", want.Domains, got.Domains},
	} {
		if difference := cmp.Diff(part.want, part.got); difference != "" {
			t.Fatalf("%s after the diff (-desired +migrated):\n%s", part.name, difference)
		}
	}
}

// applied is a fresh dev database with the schema applied, in namespace app
// when the schema does not create its own.
func applied(ctx context.Context, t *testing.T, server *devdb.Server, namespaces []string, ddl string) *devdb.Database {
	t.Helper()

	database, err := server.Database(ctx)
	if err != nil {
		t.Fatal(err)
	}

	t.Cleanup(func() { _ = database.Drop(context.WithoutCancel(ctx)) })

	if namespaces[0] == "app" {
		ddl = "CREATE SCHEMA app;\n" + ddl
	}

	if _, err := database.Pool.Exec(ctx, ddl); err != nil {
		t.Fatalf("apply: %v\n%s", err, ddl)
	}

	return database
}

func render(ctx context.Context, t *testing.T, database *devdb.Database, namespaces []string) introspect.Rendering {
	t.Helper()

	rendering, err := introspect.Render(ctx, database.Pool, namespaces)
	if err != nil {
		t.Fatal(err)
	}

	return rendering
}
