// TestLockTable replays every lock table entry and compares the locks
// PostgreSQL grants and whether the relation was rewritten with Assess.
func TestLockTable(t *testing.T) {
	t.Parallel()

	for _, major := range []int{16, 17, 18} {
		t.Run(strconv.Itoa(major), func(t *testing.T) {
			t.Parallel()

			pool := postgresPool(t, major)

			ctx, cancel := context.WithTimeout(t.Context(), 5*startupTimeout)
			defer cancel()

			server, err := devdb.Start(ctx, config.Dev{URL: pool.Config().ConnString()})
			if err != nil {
				t.Fatal(err)
			}

			defer func() { _ = server.Close(context.WithoutCancel(ctx)) }()

			for _, item := range lockSamples() {
				if major < item.minMajor {
					continue
				}

				t.Run(string(item.operation.Kind)+"/"+item.sql, func(t *testing.T) {
					checkLocks(ctx, t, server, major, item)
				})
			}
		})
	}
}

// observation is what one statement did.
type observation struct {
	locks     map[string]migrate.LockMode
	rewritten bool
	waited    bool
}

func checkLocks(ctx context.Context, t *testing.T, server *devdb.Server, major int, item lockSample) {
	t.Helper()

	database, err := server.Database(ctx)
	if err != nil {
		t.Fatal(err)
	}

	t.Cleanup(func() { _ = database.Drop(context.WithoutCancel(ctx)) })

	if _, err := database.Pool.Exec(ctx, lockFixture+";"+item.setup); err != nil {
		t.Fatalf("fixture: %v", err)
	}

	if item.pending {
		interruptDetach(ctx, t, database.Pool)
	}

	names := relations(ctx, t, database.Pool)
	env := safety.Env{Major: major, Relations: make(map[string]safety.Relation)}

	for _, name := range names {
		env.Relations[name] = safety.Relation{}
	}

	want := safety.Assess([]safety.Operation{item.operation}, env)

	var got observation
	if want.Tx == migrate.OwnStatement {
		got = observeWaiting(ctx, t, database.Pool, item, names)
	} else {
		got = observeInTx(ctx, t, database.Pool, item, names)
	}

	compareLocks(t, item, env, want, got)

	if got.rewritten != (want.Effect == safety.Rewrite) && env.Exists(item.operation.Relation) {
		t.Errorf("rewrite: PostgreSQL %v, table effect %s", got.rewritten, want.Effect)
	}

	if want.Tx == migrate.OwnStatement && got.waited != want.Waits {
		t.Errorf("waits: PostgreSQL %v, table %v", got.waited, want.Waits)
	}
}

func modeOf(locks []migrate.RelLock, relation string) migrate.LockMode {
	for _, lock := range locks {
		if lock.Relation == relation {
			return lock.Mode
		}
	}

	return migrate.NoLock
}

// relations are the names of the fixture's relations by oid, read before the
// statement renames or drops one.
func relations(ctx context.Context, t *testing.T, pool *pgxpool.Pool) map[uint32]string {
	t.Helper()

	rows, err := pool.Query(ctx, `SELECT c.oid, n.nspname || '.' || c.relname FROM pg_class c
		JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'app'`)
	if err != nil {
		t.Fatal(err)
	}

	defer rows.Close()

	result := make(map[uint32]string)

	for rows.Next() {
		var (
			oid  uint32
			name string
		)

		if err := rows.Scan(&oid, &name); err != nil {
			t.Fatal(err)
		}

		result[oid] = name
	}

	return result
}

// compareLocks checks the locks PostgreSQL took on the operation's relations
// against the table; a phased operation may take weaker ones.
func compareLocks(t *testing.T, item lockSample, env safety.Env, want safety.Safety, got observation) {
	t.Helper()

	for _, relation := range []string{item.operation.Relation, item.operation.Other} {
		if relation == "" || !env.Exists(relation) {
			continue
		}

		expected := modeOf(want.Locks, relation)
		if got.locks[relation] != expected && (!item.phased || got.locks[relation] >= expected) {
			t.Errorf("lock on %s: PostgreSQL %s, table %s", relation, got.locks[relation], expected)
		}
	}
}

// heldLocks is every granted relation lock of a backend.
const heldLocks = `SELECT l.relation, l.mode FROM pg_locks l
	WHERE l.pid = $1 AND l.locktype = 'relation' AND l.granted`

func collectLocks(ctx context.Context, t *testing.T, query interface {
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
}, pid uint32, names map[uint32]string,
) map[string]migrate.LockMode {
	t.Helper()

	rows, err := query.Query(ctx, heldLocks, pid)
	if err != nil {
		t.Fatal(err)
	}

	defer rows.Close()

	result := make(map[string]migrate.LockMode)

	for rows.Next() {
		var (
			oid  uint32
			mode string
		)

		if err := rows.Scan(&oid, &mode); err != nil {
			t.Fatal(err)
		}

		if name, ok := names[oid]; ok {
			result[name] = max(result[name], lockMode(mode))
		}
	}

	return result
}

func lockMode(name string) migrate.LockMode {
	for mode := migrate.AccessShare; mode <= migrate.AccessExclusive; mode++ {
		if mode.String()+"Lock" == name {
			return mode
		}
	}

	return migrate.NoLock
}

func relfilenode(ctx context.Context, t *testing.T, query interface {
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}, relation string,
) uint32 {
	t.Helper()

	if relation == "" {
		return 0
	}

	var node uint32

	// Sequences get a new file on every ALTER; only table data is rewritten.
	err := query.QueryRow(ctx, `SELECT COALESCE((SELECT relfilenode FROM pg_class
		WHERE oid = to_regclass($1) AND relkind IN ('r', 'm')), 0)`, relation).Scan(&node)
	if err != nil {
		t.Fatal(err)
	}

	return node
}

// observeInTx runs the statement in a transaction and reads its own locks
// before rolling back.
func observeInTx(
	ctx context.Context, t *testing.T, pool *pgxpool.Pool, item lockSample, names map[uint32]string,
) observation {
	t.Helper()

	transaction, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}

	defer func() { _ = transaction.Rollback(context.WithoutCancel(ctx)) }()

	before := relfilenode(ctx, t, transaction, item.operation.Relation)

	if _, err := transaction.Exec(ctx, item.sql); err != nil {
		t.Fatalf("statement: %v", err)
	}

	pid := transaction.Conn().PgConn().PID()
	result := observation{locks: collectLocks(ctx, t, transaction, pid, names)}
	after := relfilenode(ctx, t, transaction, item.operation.Relation)
	result.rewritten = before != after && after != 0

	return result
}

// observeWaiting runs a statement that cannot run in a transaction while
// another transaction holds a row lock on its relation, reads the locks it
// holds while it waits for that transaction, then lets it finish.
func observeWaiting(
	ctx context.Context, t *testing.T, pool *pgxpool.Pool, item lockSample, names map[uint32]string,
) observation {
	t.Helper()

	blocked := item.operation.Relation
	if item.operation.Other != "" {
		blocked = item.operation.Other
	}

	blocker, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}

	defer func() { _ = blocker.Rollback(context.WithoutCancel(ctx)) }()

	if _, err := blocker.Exec(ctx, "LOCK TABLE "+blocked+" IN ROW EXCLUSIVE MODE"); err != nil {
		t.Fatal(err)
	}

	connection, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}

	defer connection.Release()

	pid := connection.Conn().PgConn().PID()
	done := make(chan error, 1)

	go func() {
		_, err := connection.Exec(ctx, item.sql)
		done <- err
	}()

	result := observation{waited: waitsFor(ctx, t, pool, pid, done)}
	result.locks = collectLocks(ctx, t, pool, pid, names)

	if err := blocker.Rollback(ctx); err != nil {
		t.Fatal(err)
	}

	if err := <-done; err != nil && !errors.Is(err, errFinished) {
		t.Fatalf("statement: %v", err)
	}

	return result
}

var errFinished = errors.New("finished")

// waitsFor reports whether the backend starts waiting for a lock before its
// statement finishes.
func waitsFor(ctx context.Context, t *testing.T, pool *pgxpool.Pool, pid uint32, done chan error) bool {
	t.Helper()

	deadline := time.Now().Add(10 * time.Second)

	for time.Now().Before(deadline) {
		select {
		case err := <-done:
			if err != nil {
				t.Fatalf("statement: %v", err)
			}

			done <- errFinished

			return false
		default:
		}

		var waiting bool

		err := pool.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM pg_locks WHERE pid = $1 AND NOT granted)`,
			pid).Scan(&waiting)
		if err != nil {
			t.Fatal(err)
		}

		if waiting {
			return true
		}

		time.Sleep(10 * time.Millisecond)
	}

	t.Fatal("statement neither waited nor finished")

	return false
}
