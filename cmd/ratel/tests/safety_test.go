// lockSample replays one table entry: setup runs first and is not observed.
// A phased statement commits its first phase before it waits, so the locks
// seen while it waits are a subset of the table's.
type lockSample struct {
	operation safety.Operation
	setup     string
	sql       string
	minMajor  int
	phased    bool
	// pending interrupts a concurrent detach of app.p1 before the statement.
	pending bool
}

func (s lockSample) phases() lockSample {
	s.phased = true

	return s
}

func (s lockSample) interrupted() lockSample {
	s.pending = true

	return s
}

// interruptDetach leaves the detach of app.p1 pending: the concurrent detach
// times out while a transaction still uses the partition.
func interruptDetach(ctx context.Context, t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	blocker, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}

	defer func() { _ = blocker.Rollback(context.WithoutCancel(ctx)) }()

	if _, err := blocker.Exec(ctx, `LOCK TABLE app.p1 IN ROW EXCLUSIVE MODE`); err != nil {
		t.Fatal(err)
	}

	connection, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}

	// The timed-out session is not returned to the pool.
	defer connection.Hijack()

	_, err = connection.Exec(ctx, `SET statement_timeout = '300ms'`)
	if err == nil {
		_, err = connection.Exec(ctx, `ALTER TABLE app.p DETACH PARTITION app.p1 CONCURRENTLY`)
	}

	if err == nil {
		t.Fatal("concurrent detach finished while the partition was in use")
	}
}

func sample(kind safety.Kind, relation, other, sql string) lockSample {
	return lockSample{operation: safety.Operation{Kind: kind, Relation: relation, Other: other}, sql: sql}
}

func (s lockSample) after(setup string) lockSample {
	s.setup = setup

	return s
}

func (s lockSample) rewrites() lockSample {
	s.operation.Rewrite = true

	return s
}

func (s lockSample) since(major int) lockSample {
	s.minMajor = major

	return s
}

