// Package gengo is ratel-gen-go, the Go output plugin. It speaks the plugin
// protocol only, so the built-in generator uses nothing a third-party plugin
// cannot: the host links it in and calls it through the same messages.
package gengo

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"go/format"
	"path"
	"slices"
	"strings"

	"github.com/gopherex/ratel/ir"
	"github.com/gopherex/ratel/plugin"
	"github.com/gopherex/ratel/plugin/pluginpb"
)

// Name is the plugin name and its annotation namespace.
const Name = "go"

const (
	protocolVersion = 1
	version         = "0.1.0"
)

// Options are the plugin options of ratel.yaml.
type Options struct {
	// ImportPath is the Go import path of the output directory. Schema and
	// query packages are its subdirectories.
	ImportPath string `json:"import_path"`
	// Types maps a PostgreSQL type name ("jsonb", "app.money") to a Go type
	// ("github.com/acme/doc.Document"), overriding the default mapping.
	Types map[string]string `json:"types"`
}

// Generator is the ratel-gen-go plugin.
type Generator struct{}

// Info describes the plugin.
func (Generator) Info(context.Context, *pluginpb.InfoRequest) (*pluginpb.InfoResponse, error) {
	return &pluginpb.InfoResponse{
		Name: Name, Version: version, AnnotationNamespace: Name,
		MinProtocolVersion: protocolVersion, MaxProtocolVersion: protocolVersion,
		OptionsDescription: "import_path (required): Go import path of out; " +
			"types: PostgreSQL type name to Go type (import/path.Type)",
	}, nil
}

// Generate returns one Go file per schema package and query package.
func (Generator) Generate(ctx context.Context, request *pluginpb.GenerateRequest) (*pluginpb.GenerateResponse, error) {
	options, err := decodeOptions(request.GetOptions())
	if err != nil {
		return nil, err
	}

	state, err := newState(options, request)
	if err != nil {
		return nil, err
	}

	var files []*pluginpb.File

	for _, schema := range request.GetCatalog().GetSchemas() {
		if err := ctx.Err(); err != nil {
			return nil, fmt.Errorf("ratel-gen-go: %w", err)
		}

		rendered, err := state.schemaFiles(schema)
		if err != nil {
			return nil, err
		}

		files = append(files, rendered...)
	}

	queries, err := state.queryFiles(request.GetQueries())
	if err != nil {
		return nil, err
	}

	return &pluginpb.GenerateResponse{Files: append(files, queries...), Diagnostics: state.warnings}, nil
}

func decodeOptions(data []byte) (Options, error) {
	var options Options

	if len(data) > 0 && !bytes.Equal(data, []byte("null")) {
		decoder := json.NewDecoder(bytes.NewReader(data))
		decoder.DisallowUnknownFields()

		if err := decoder.Decode(&options); err != nil {
			return Options{}, &plugin.Error{Code: "RTL-G01", Message: "invalid options: " + err.Error()}
		}
	}

	if options.ImportPath == "" || strings.HasSuffix(options.ImportPath, "/") {
		return Options{}, &plugin.Error{Code: "RTL-G01", Message: "options.import_path is required"}
	}

	return options, nil
}

// source renders a generated file: header, imports and gofmt.
func source(packageName string, imports []string, body string) ([]byte, error) {
	var out strings.Builder

	out.WriteString("// Code generated by ratel-gen-go. DO NOT EDIT.\n\npackage " + packageName + "\n\n")

	imports = slices.Compact(slices.Sorted(slices.Values(imports)))
	if len(imports) > 0 {
		out.WriteString("import (\n")

		// The standard library first, as goimports groups it.
		standard := func(item string) bool { return !strings.Contains(strings.Split(item, "/")[0], ".") }

		for _, group := range []bool{true, false} {
			for _, item := range imports {
				if standard(item) == group {
					out.WriteString("\t" + quoteImport(item) + "\n")
				}
			}

			out.WriteString("\n")
		}

		out.WriteString(")\n\n")
	}

	out.WriteString(body)

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, &plugin.Error{Code: "RTL-G02", Message: "generated invalid Go: " + err.Error()}
	}

	return formatted, nil
}

// quoteImport names an import whose last element is not its package name.
func quoteImport(importPath string) string {
	name := importName(importPath)
	importPath, _, explicit := strings.Cut(importPath, ";")

	if base := importBase(importPath); !explicit && (name == base || strings.ReplaceAll(base, "-", "") == name) {
		return `"` + importPath + `"`
	}

	return name + ` "` + importPath + `"`
}

// importName is the package name code uses for an import: the name after ";"
// when given (a proto go_package), else its base made a valid identifier.
func importName(importPath string) string {
	if _, name, explicit := strings.Cut(importPath, ";"); explicit {
		return name
	}

	return packageName(importBase(importPath))
}

// importBase is the last path element, or the one before a major-version
// element (github.com/jackc/pgx/v5 is pgx).
func importBase(importPath string) string {
	base := path.Base(importPath)
	if strings.HasPrefix(base, "v") && len(base) > 1 && strings.Trim(base[1:], "0123456789") == "" {
		return path.Base(path.Dir(importPath))
	}

	return base
}

// schemaOf and objectOf split a schema-qualified PostgreSQL name.
func schemaOf(name *ir.QualifiedName) string { return name.GetParts()[0] }

func objectOf(name *ir.QualifiedName) string {
	parts := name.GetParts()

	return parts[len(parts)-1]
}
