func TestMapDDL(t *testing.T) {
	parse.Warm()
	t.Parallel()

	for _, tc := range []struct {
		sql   string
		check func(*testing.T, mapper.Mapper, *pg.Node)
	}{
		{"CREATE TABLE app.t (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY," +
			" name varchar(20) NOT NULL DEFAULT 'x', n int GENERATED ALWAYS AS (id+1) STORED," +
			" CONSTRAINT positive CHECK (id>0)," +
			" CONSTRAINT fk FOREIGN KEY(id) REFERENCES app.u(id) ON DELETE SET NULL (id))", checkTable},
		{"CREATE UNLOGGED TABLE app.t (id int, CONSTRAINT pk PRIMARY KEY(id)) PARTITION BY RANGE(id)", checkTable},
		{"CREATE TABLE app.part PARTITION OF app.t FOR VALUES FROM (1) TO (10)", checkTable},
		{"CREATE TABLE app.t (id int, EXCLUDE USING gist (id WITH =))", checkTable},
		{"CREATE UNIQUE INDEX idx ON app.t USING btree" +
			" (name COLLATE app.c text_ops DESC NULLS LAST, (lower(name))) INCLUDE (id) WHERE id > 0", checkIndex},
		{"CREATE VIEW app.v(x) WITH (security_barrier=true)" +
			" AS SELECT id FROM app.t WITH LOCAL CHECK OPTION", checkView},
		{"CREATE TYPE app.status AS ENUM ('', 'active', 'deleted')", checkEnum},
		{"CREATE SEQUENCE app.seq AS bigint START 9223372036854775806 INCREMENT -2" +
			" MINVALUE -10 MAXVALUE 9223372036854775807 CACHE 3 CYCLE OWNED BY app.t.id", checkSequence},
	} {
		t.Run(tc.sql, func(t *testing.T) {
			t.Parallel()

			tree, err := parse.Parse(tc.sql)
			if err != nil {
				t.Fatal(err)
			}

			raw := tree.GetStmts()[0]
			current := mapper.New("schema.sql", tc.sql, raw, 0)
			tc.check(t, current, raw.GetStmt())
		})
	}
}

func checkTable(t *testing.T, current mapper.Mapper, node *pg.Node) {
	t.Helper()

	got := current.MapCreateTable(node.GetCreateStmt())
	if got.GetMeta().GetSource() == nil || len(got.GetName().GetParts()) != 2 {
		t.Fatal(got)
	}

	for _, column := range got.GetColumns() {
		if column.GetMeta().GetSource() == nil || column.GetPosition() == 0 {
			t.Fatal(column)
		}
	}

	for _, constraint := range got.GetConstraints() {
		if !constraint.GetValidated() {
			t.Fatal("new constraint not validated", constraint)
		}
	}

	if node.GetCreateStmt().GetPartspec() != nil && got.GetPartitionBy() == "" {
		t.Fatal("partition key lost")
	}

	if node.GetCreateStmt().GetPartbound() != nil && got.GetPartitionBound() == "" {
		t.Fatal("partition bound lost")
	}
}

func checkIndex(t *testing.T, current mapper.Mapper, node *pg.Node) {
	t.Helper()

	got := current.MapIndex(node.GetIndexStmt())
	if !got.GetReady() || !got.GetValid() || len(got.GetElements()) != 2 || got.GetPredicate() == nil {
		t.Fatal(got)
	}
}

func checkView(t *testing.T, current mapper.Mapper, node *pg.Node) {
	t.Helper()

	got := current.MapView(node.GetViewStmt())
	if !got.GetSecurityBarrier() || got.GetQuery() == nil {
		t.Fatal(got)
	}
}

func checkEnum(t *testing.T, current mapper.Mapper, node *pg.Node) {
	t.Helper()

	got := current.MapCreateEnum(node.GetCreateEnumStmt())
	if len(got.GetLabels()) != 3 || got.GetLabels()[0] != "" {
		t.Fatal(got)
	}
}

func checkSequence(t *testing.T, current mapper.Mapper, node *pg.Node) {
	t.Helper()

	got := current.MapCreateSequence(node.GetCreateSeqStmt())
	if got.GetStart() != 9223372036854775806 || got.GetMaxValue() != 9223372036854775807 ||
		got.GetIncrement() != -2 || !got.GetCycle() || len(got.GetOwnedBy().GetName().GetParts()) != 3 {
		t.Fatal(got)
	}
}

func TestColumnConstraints(t *testing.T) {
	parse.Warm()
	t.Parallel()

	for _, tc := range []struct {
		declaration string
		nullable    bool
		constraint  string
	}{
		{"id int NOT NULL", false, "NOT_NULL"},
		{"id int PRIMARY KEY", false, "PRIMARY_KEY"},
		{"id int UNIQUE NULLS NOT DISTINCT", true, "UNIQUE"},
		{"id int REFERENCES app.u(id) MATCH FULL ON DELETE CASCADE ON UPDATE RESTRICT", true, "FOREIGN_KEY"},
		{"id int CHECK (id>0)", true, "CHECK"},
		{"id int DEFAULT 1", true, ""},
		{"id int GENERATED BY DEFAULT AS IDENTITY (START 3)", false, ""},
	} {
		t.Run(tc.declaration, func(t *testing.T) {
			t.Parallel()

			sql := "CREATE TABLE app.t (" + tc.declaration + ")"

			tree, err := parse.Parse(sql)
			if err != nil {
				t.Fatal(err)
			}

			raw := tree.GetStmts()[0]
			current := mapper.New("column.sql", sql, raw, 0)
			column := raw.GetStmt().GetCreateStmt().GetTableElts()[0].GetColumnDef()

			got := current.MapColumn(column, 1)
			if got.GetNullable() != tc.nullable || got.GetPosition() != 1 {
				t.Fatal(got)
			}

			constraint := current.MapConstraint(column.GetConstraints()[0].GetConstraint(), "id")
			if tc.constraint == "" {
				if constraint != nil {
					t.Fatal(constraint)
				}
			} else if constraint.GetType().String() != "CONSTRAINT_TYPE_"+tc.constraint {
				t.Fatal(constraint)
			}
		})
	}
}

func BenchmarkDDL(b *testing.B) {
	sql := "CREATE TABLE app.t (id bigint PRIMARY KEY, amount numeric(12,2) DEFAULT 0 CHECK (amount>=0))"

	tree, err := parse.Parse(sql)
	if err != nil {
		b.Fatal(err)
	}

	raw := tree.GetStmts()[0]
	current := mapper.New("bench.sql", sql, raw, 0)

	for b.Loop() {
		current.MapCreateTable(raw.GetStmt().GetCreateStmt())
	}
}
