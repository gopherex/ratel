type writeRecord struct {
	ID     int64
	Email  string
	Note   ratel.Null[string]
	Parent ratel.Null[int64]
	Score  int64
	Period pgtype.Range[int64]
	Labels []int64
}

type recordInsert struct {
	email  string
	valid  bool
	ID     ratel.Opt[int64]
	Note   ratel.Opt[ratel.Null[string]]
	Parent ratel.Null[int64]
	Score  ratel.Opt[int64]
	Period ratel.Opt[pgtype.Range[int64]]
	Labels ratel.Opt[[]int64]
}

func newRecordInsert(email string) recordInsert { return recordInsert{email: email, valid: true} }

type writeRecords struct {
	ratel.WriteTable[writeRecord, recordInsert]
	ID     ratel.Col[writeRecord, int64]
	Email  ratel.Col[writeRecord, string]
	Note   ratel.NullCol[writeRecord, string]
	Parent ratel.NullCol[writeRecord, int64]
	Score  ratel.Col[writeRecord, int64]
}

func recordDescriptor() writeRecords {
	table := ratel.NewTable("write_app", "records",
		[]string{"id", "email", "note", "parent_id", "score", "period", "labels"}, scanWriteRecord,
		ratel.Constraints[writeRecord](ratel.ConstraintError{Constraint: "records_email_key", Columns: []string{"email"}}))

	return writeRecords{
		WriteTable: ratel.NewWriteTable(table, func(row recordInsert) bool { return row.valid },
			ratel.InsertField[recordInsert]{
				Name: "email", Type: pgx.Identifier{"pg_catalog", "text"},
				Value: func(row recordInsert) (any, bool) { return row.email, true },
				Values: func(rows []recordInsert) any {
					return recordArray(rows, func(row recordInsert) string { return row.email })
				},
			},
			ratel.InsertField[recordInsert]{
				Name: "id", Type: pgx.Identifier{"pg_catalog", "int8"},
				Value: func(row recordInsert) (any, bool) { return row.ID.V, row.ID.Set },
				Values: func(rows []recordInsert) any {
					return recordArray(rows, func(row recordInsert) int64 { return row.ID.V })
				},
			},
			ratel.InsertField[recordInsert]{
				Name: "note", Type: pgx.Identifier{"pg_catalog", "text"},
				Value: func(row recordInsert) (any, bool) { return row.Note.V, row.Note.Set },
				Values: func(rows []recordInsert) any {
					return recordArray(rows, func(row recordInsert) pgtype.Text {
						return pgtype.Text{String: row.Note.V.V, Valid: row.Note.V.Valid}
					})
				},
			},
			ratel.InsertField[recordInsert]{
				Name: "parent_id", Type: pgx.Identifier{"pg_catalog", "int8"},
				Value: func(row recordInsert) (any, bool) { return row.Parent, true },
				Values: func(rows []recordInsert) any {
					return recordArray(rows, func(row recordInsert) pgtype.Int8 {
						return pgtype.Int8{Int64: row.Parent.V, Valid: row.Parent.Valid}
					})
				},
			},
			ratel.InsertField[recordInsert]{
				Name: "score", Type: pgx.Identifier{"pg_catalog", "int8"},
				Value: func(row recordInsert) (any, bool) { return row.Score.V, row.Score.Set },
				Values: func(rows []recordInsert) any {
					return recordArray(rows, func(row recordInsert) int64 { return row.Score.V })
				},
			},
			ratel.InsertField[recordInsert]{
				Name: "period", Type: pgx.Identifier{"pg_catalog", "int8range"},
				Value: func(row recordInsert) (any, bool) { return row.Period.V, row.Period.Set },
				Values: func(rows []recordInsert) any {
					return recordArray(rows, func(row recordInsert) pgtype.Range[int64] { return row.Period.V })
				},
			},
			ratel.InsertField[recordInsert]{
				Name: "labels", Type: pgx.Identifier{"pg_catalog", "_int8"},
				Value: func(row recordInsert) (any, bool) { return row.Labels.V, row.Labels.Set },
			}),
		ID: ratel.NewCol[writeRecord, int64]("id"), Email: ratel.NewCol[writeRecord, string]("email"),
		Note: ratel.NewNullCol[writeRecord, string]("note"), Parent: ratel.NewNullCol[writeRecord, int64]("parent_id"),
		Score: ratel.NewCol[writeRecord, int64]("score"),
	}
}

func recordArray[V any](rows []recordInsert, value func(recordInsert) V) []V {
	values := make([]V, len(rows))
	for index := range rows {
		values[index] = value(rows[index])
	}

	return values
}

func scanWriteRecord(row pgx.Row) (writeRecord, error) {
	var record writeRecord
	err := row.Scan(&record.ID, &record.Email, &record.Note, &record.Parent, &record.Score, &record.Period, &record.Labels)

	return record, err
}

func writePool(tb testing.TB) *pgxpool.Pool {
	tb.Helper()
	pool := valuePool(tb)

	ctx, cancel := context.WithTimeout(tb.Context(), containerWait)
	defer cancel()

	_, err := pool.Exec(ctx, `CREATE SCHEMA write_app;
 CREATE TABLE write_app.parents(id bigint PRIMARY KEY);
 INSERT INTO write_app.parents VALUES (1);
 CREATE TABLE write_app.records (
 id bigint GENERATED BY DEFAULT AS IDENTITY,
 email text NOT NULL UNIQUE,
 note text DEFAULT 'default',
 parent_id bigint REFERENCES write_app.parents,
 score bigint NOT NULL DEFAULT 1 CHECK (score > 0),
 period int8range, labels bigint[],
 EXCLUDE USING gist (period WITH &&));
 CREATE FUNCTION write_app.before_write() RETURNS trigger LANGUAGE plpgsql AS $$
 BEGIN
 NEW.email := lower(NEW.email);
 IF NEW.email = 'hang' THEN PERFORM pg_catalog.pg_advisory_xact_lock(9911); END IF;
 RETURN NEW;
 END $$;
 CREATE TRIGGER normalize BEFORE INSERT OR UPDATE ON write_app.records
 FOR EACH ROW EXECUTE FUNCTION write_app.before_write();`)
	if err != nil {
		tb.Fatal(err)
	}

	return pool
}

func TestWriteRuntime(t *testing.T) {
	t.Parallel()
	pool := writePool(t)

	for _, tc := range []struct {
		name string
		run  func(*testing.T, *pgxpool.Pool)
	}{
		{"insert protocols and returning", writeInsertModes},
		{"upsert protocols", writeUpsertModes},
		{"update delete without primary key", writeMutations},
		{"constraints", writeConstraints},
		{"chunk atomicity", writeChunkAtomicity},
		{"connection kill mid-write", writeConnectionKill},
	} {
		t.Run(tc.name, func(t *testing.T) { t.Parallel(); tc.run(t, pool) })
	}
}

func writeInsertModes(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	records := recordDescriptor()
	database := ratel.New(pool)

	for _, mode := range []pgx.QueryExecMode{
		pgx.QueryExecModeCacheStatement, pgx.QueryExecModeCacheDescribe,
		pgx.QueryExecModeExec, pgx.QueryExecModeSimpleProtocol,
	} {
		prefix := "insert-" + mode.String()
		first := newRecordInsert(strings.ToUpper(prefix) + "-a")
		second := newRecordInsert(prefix + "-b")
		second.Note = ratel.OptFrom(ratel.Null[string]{})
		third := newRecordInsert(prefix + "-c")
		third.Note = ratel.OptFrom(ratel.NullFrom("custom"))

		rows, err := database.Run(records.Insert(first, second, third).Chunk(2).Returning()).
			List(t.Context(), ratel.ExecMode(mode))
		if err != nil || len(rows) != 3 {
			t.Fatalf("%v: %+v %v", mode, rows, err)
		}

		if rows[0].Email != prefix+"-a" || rows[0].ID == 0 || rows[0].Note.V != "default" ||
			rows[1].Note.Valid || rows[2].Note.V != "custom" {
			t.Fatalf("RETURNING ignored defaults, nulls or BEFORE trigger: %+v", rows)
		}
		// Array-valued columns must preserve nested array boundaries and NULL arrays.
		first = newRecordInsert(prefix + "-array-a")
		first.Labels = ratel.OptFrom([]int64{1, 2})
		second = newRecordInsert(prefix + "-array-b")
		second.Labels = ratel.OptFrom([]int64(nil))

		rows, err = database.Run(records.Insert(first, second).Chunk(2).Returning()).List(t.Context(), ratel.ExecMode(mode))
		if err != nil || len(rows) != 2 || len(rows[0].Labels) != 2 || rows[1].Labels != nil {
			t.Fatalf("%+v %v", rows, err)
		}
	}
}

func writeUpsertModes(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	records := recordDescriptor()
	database := ratel.New(pool)

	for _, mode := range []pgx.QueryExecMode{
		pgx.QueryExecModeCacheStatement, pgx.QueryExecModeCacheDescribe,
		pgx.QueryExecModeExec, pgx.QueryExecModeSimpleProtocol,
	} {
		first := newRecordInsert("upsert-" + mode.String() + "-a")
		second := newRecordInsert("upsert-" + mode.String() + "-b")
		first.Note = ratel.OptFrom(ratel.NullFrom("old"))
		second.Note = first.Note

		initial, err := database.Run(records.Insert(first, second).Returning()).List(t.Context(), ratel.ExecMode(mode))
		if err != nil {
			t.Fatal(err)
		}

		first.Note = ratel.OptFrom(ratel.NullFrom("new"))
		second.Note = first.Note
		query := records.Upsert(first, second).OnConflict(records.Email).Update(records.Note)

		statement, _, err := query.Build()
		if err != nil || !strings.Contains(statement, "unnest(") {
			t.Fatalf("%+v %v", statement, err)
		}

		rows, err := database.Run(query.Returning()).List(t.Context(), ratel.ExecMode(mode))
		if err != nil || len(rows) != 2 || rows[0].ID != initial[0].ID || rows[0].Note.V != "new" {
			t.Fatalf("%+v %v", rows, err)
		}

		count, err := database.Run(records.Upsert(first, second).OnConflict(records.Email).DoNothing()).
			Exec(t.Context(), ratel.ExecMode(mode))
		if err != nil || count != 0 {
			t.Fatalf("%d %v", count, err)
		}
	}
}

func writeMutations(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	records := recordDescriptor()
	database := ratel.New(pool)

	rows, err := database.Run(records.Insert(newRecordInsert("mutate")).Returning()).List(t.Context())
	if err != nil {
		t.Fatal(err)
	}

	identity := rows[0].ID

	rows, err = database.Run(records.Update().Set(records.Note.To(ratel.NullFrom("changed"))).
		Where(records.ID.Eq(identity)).
		Where(records.Email.Eq("mutate")).Returning()).List(t.Context())
	if err != nil || len(rows) != 1 || rows[0].Note.V != "changed" {
		t.Fatalf("%+v %v", rows, err)
	}

	rows, err = database.Run(records.Delete().Where(records.ID.Eq(identity)).Returning()).List(t.Context())
	if err != nil || len(rows) != 1 || rows[0].ID != identity {
		t.Fatalf("%+v %v", rows, err)
	}

	count, err := database.Run(records.Delete().Where(records.ID.Eq(identity))).Exec(t.Context())
	if err != nil || count != 0 {
		t.Fatalf("%d %v", count, err)
	}
}

func writeConstraints(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	records := recordDescriptor()
	database := ratel.New(pool)
	seed := newRecordInsert("constraint-seed")
	seed.Period = ratel.OptFrom(pgtype.Range[int64]{
		Lower: 1, Upper: 5, LowerType: pgtype.Inclusive, UpperType: pgtype.Exclusive, Valid: true,
	})

	if _, err := database.Run(records.Insert(seed)).Exec(t.Context()); err != nil {
		t.Fatal(err)
	}

	cases := []struct {
		name string
		kind ratel.ConstraintKind
		row  recordInsert
	}{
		{"unique", ratel.ConstraintUnique, newRecordInsert(seed.email)},
		{"foreign key", ratel.ConstraintForeignKey, func() recordInsert {
			row := newRecordInsert("bad-fk")
			row.Parent = ratel.NullFrom(int64(999))

			return row
		}()},
		{"check", ratel.ConstraintCheck, func() recordInsert {
			row := newRecordInsert("bad-check")
			row.Score = ratel.OptFrom(int64(-1))

			return row
		}()},
		{"exclusion", ratel.ConstraintExclusion, func() recordInsert {
			row := newRecordInsert("bad-range")
			row.Period = seed.Period

			return row
		}()},
	}

	for index := range cases {
		tc := &cases[index]
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			_, err := database.Run(records.Insert(tc.row).Returning()).List(t.Context())

			var constraint *ratel.ConstraintError

			var driver *pgconn.PgError
			if !errors.As(err, &constraint) || !errors.As(err, &driver) || constraint.Kind != tc.kind {
				t.Fatalf("%T %v", err, err)
			}

			sentinel := &ratel.ConstraintError{
				Kind: tc.kind, Schema: "write_app", Table: "records", Constraint: constraint.Constraint,
			}
			if !errors.Is(err, sentinel) {
				t.Fatalf("sentinel mismatch: %v", err)
			}

			if tc.kind == ratel.ConstraintUnique && (len(constraint.Columns) != 1 || constraint.Columns[0] != "email") {
				t.Fatalf("missing generated columns: %+v", constraint)
			}
		})
	}
	// A nullable assignment can still reach a NOT NULL column through generated metadata.
	_, err := database.Run(records.Update().Set(ratel.NewNullCol[writeRecord, string]("email").To(ratel.Null[string]{})).
		Where(records.Email.Eq(seed.email))).Exec(t.Context())

	var constraint *ratel.ConstraintError

	if !errors.As(err, &constraint) || constraint.Kind != ratel.ConstraintNotNull {
		t.Fatalf("%v", err)
	}
}

func writeChunkAtomicity(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	records := recordDescriptor()
	if _, err := ratel.New(pool).Run(records.Insert(newRecordInsert("chunk-existing"))).Exec(t.Context()); err != nil {
		t.Fatal(err)
	}

	for _, transactional := range []bool{false, true} {
		t.Run(fmt.Sprintf("transaction=%v", transactional), func(t *testing.T) {
			t.Parallel()

			var executor ratel.Executor = pool

			rollback := func() {}

			if transactional {
				transaction, err := pool.Begin(t.Context())
				if err != nil {
					t.Fatal(err)
				}

				executor = transaction
				rollback = func() { _ = transaction.Rollback(t.Context()) }
			}

			defer rollback()

			email := fmt.Sprintf("chunk-%v", transactional)
			query := records.Insert(newRecordInsert(email), newRecordInsert("chunk-existing")).Chunk(1)
			rows, err := ratel.New(executor).Run(query.Returning()).List(t.Context())

			var constraint *ratel.ConstraintError
			if !errors.As(err, &constraint) || constraint.Kind != ratel.ConstraintUnique || rows != nil {
				t.Fatalf("partial result: %+v %v", rows, err)
			}

			rollback()

			models, err := ratel.New(pool).Run(records.Select().Where(records.Email.Eq(email))).List(t.Context())
			want := 1

			if transactional {
				want = 0
			}

			if err != nil || len(models) != want {
				t.Fatalf("committed rows=%d, want=%d: %v", len(models), want, err)
			}
		})
	}
}

func writeConnectionKill(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()

	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Second)
	defer cancel()

	blocker, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}

	defer blocker.Release()

	if _, err = blocker.Exec(ctx, "SELECT pg_catalog.pg_advisory_lock(9911)"); err != nil {
		t.Fatal(err)
	}

	defer func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.WithoutCancel(ctx), time.Second)
		defer cleanupCancel()

		if _, cleanupErr := blocker.Exec(cleanupCtx, "SELECT pg_catalog.pg_advisory_unlock(9911)"); cleanupErr != nil {
			t.Error(cleanupErr)
		}
	}()

	victim, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}

	defer victim.Release()
	pid := victim.Conn().PgConn().PID()
	done := make(chan struct{})
	result := make(chan error, 1)

	go func() {
		defer close(done)

		_, failure := ratel.New(victim.Conn()).Run(recordDescriptor().Insert(newRecordInsert("hang"))).Exec(ctx)
		result <- failure
	}()

	defer func() { cancel(); <-done }()

	waitWriteLock(ctx, t, pool, pid)

	var terminated bool

	err = pool.QueryRow(ctx, "SELECT pg_catalog.pg_terminate_backend($1)", pid).Scan(&terminated)
	if err != nil || !terminated {
		t.Fatalf("%v %v", terminated, err)
	}

	failure := <-result

	var driver *pgconn.PgError

	var refusal *ratel.ConstraintError
	if !errors.As(failure, &driver) || driver.Code != "57P01" || errors.As(failure, &refusal) {
		t.Fatalf("lost technical failure: %v", failure)
	}

	var count int

	err = pool.QueryRow(ctx, "SELECT count(*) FROM write_app.records WHERE email='hang'").Scan(&count)
	if err != nil || count != 0 {
		t.Fatalf("partial write: %d %v", count, err)
	}

	query := recordDescriptor().Insert(newRecordInsert(fmt.Sprintf("recovered-%d", pid)))
	if _, err = ratel.New(pool).Run(query).Exec(ctx); err != nil {
		t.Fatal(err)
	}
}

func waitWriteLock(ctx context.Context, t *testing.T, pool *pgxpool.Pool, pid uint32) {
	t.Helper()

	for {
		var waiting bool

		err := pool.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM pg_catalog.pg_stat_activity
 WHERE pid=$1 AND wait_event_type='Lock' AND wait_event='advisory')`, pid).Scan(&waiting)
		if err != nil {
			t.Fatal(err)
		}

		if waiting {
			return
		}

		if _, err = pool.Exec(ctx, "SELECT pg_catalog.pg_sleep(0.01)"); err != nil {
			t.Fatal(err)
		}
	}
}
